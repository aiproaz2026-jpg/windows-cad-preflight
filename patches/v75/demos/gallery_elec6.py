import sys, json, os, traceback
import FreeCAD as App
sys.path.insert(0, 'C:/DeltaTest/Mod'); sys.path.insert(0, 'C:/DeltaTest/Mod/DeltaEngineering')
OUT = 'C:/seed/gallery72'; os.makedirs(OUT, exist_ok=True)
sys.path.insert(0, 'C:/DeltaTest/Mod/DeltaEngineering/DeltaEngineering')
res = {'done': False}
try:
    from DeltaEngineering.symbols import create
    from DeltaEngineering.domain import add_terminal_wire, netlist
    from DeltaEngineering.electrical import terminal_layout, set_terminal_sides
    from DeltaEngineering.core import terminal_position
    from DeltaEngineering import routecheck
    from DeltaEngineering import minipdf
    from DeltaEngineering import term_ends
    res['term_table'] = term_ends.install(); terminal_position = term_ends.terminal_position
    d = App.newDocument('VF')
    V = App.Vector
    Q = create(d, 'Breaker 3P (illustr.)', 'Q1', V(4000, 0, 0)); VFD = create(d, 'VFD block (illustr.)', 'U1', V(4500, 0, 0))
    M = create(d, 'Motor 3-phase (illustr.)', 'M1', V(5100, 0, 0))
    for x in (VFD, M): terminal_layout(d, x, list(x.Terminals), 'Left')
    set_terminal_sides(d, VFD, {'L1': 'Left', 'L2': 'Left', 'L3': 'Left', 'PE': 'Left', 'U': 'Right', 'V': 'Right', 'W': 'Right'})
    n = 0
    for a, sa, b, sb in ((Q, '2', VFD, 'L1'), (Q, '4', VFD, 'L2'), (Q, '6', VFD, 'L3'), (VFD, 'U', M, 'U1'), (VFD, 'V', M, 'V1'), (VFD, 'W', M, 'W1'), (VFD, 'PE', M, 'PE')):
        n += 1; add_terminal_wire(d, a, sa, b, sb, 'W%d' % n)
    T1 = create(d, 'Terminal (illustr.)', 'L3', V(4000, -450, 0)); F5 = create(d, 'Fuse (illustr.)', 'F5', V(4400, -450, 0))
    S1 = create(d, 'Selector switch (illustr.)', 'S1', V(4800, -450, 0)); S2 = create(d, 'Flow switch (illustr.)', 'S2', V(5200, -450, 0))
    KR = create(d, 'Relay coil (illustr.)', 'KR1', V(5600, -450, 0)); T2 = create(d, 'Terminal (illustr.)', 'N3', V(6000, -450, 0))
    H1 = create(d, 'Lamp (illustr.)', 'H1', V(5600, -720, 0))
    set_terminal_sides(d, KR, {'A1': 'Left', 'A2': 'Right'})
    for a, sa, b, sb in ((T1, '1', F5, '1'), (F5, '2', S1, '1'), (S1, '2', S2, '1'), (S2, '2', KR, 'A1'), (KR, 'A2', T2, '1'), (S2, '2', H1, 'X1'), (H1, 'X2', T2, '1')):
        n += 1; add_terminal_wire(d, a, sa, b, sb, 'W%d' % n)
    d.recompute()
    res['netlist'] = len(netlist(d)); res['route'] = routecheck.check(d)['count']
    segs = []; texts = []; xs = []; ys = []
    def add(shape, w, rgb):
        for e in shape.Edges:
            pts = e.discretize(24) if e.Curve.__class__.__name__ != 'Line' else [e.Vertexes[0].Point, e.Vertexes[-1].Point]
            segs.append(([(p.x, p.y) for p in pts], w, rgb))
            for p in pts: xs.append(p.x); ys.append(p.y)
    ndev = 0
    for o in d.Objects:
        if hasattr(o, 'DeviceType') and not o.Shape.isNull():
            add(o.Shape, 0.9, (0.08, 0.2, 0.35)); ndev += 1
            texts.append((o.Position.x - 30, o.Position.y + 50, o.Tag))
            for t in o.Terminals:
                p = terminal_position(o, t); texts.append((p.x + 4, p.y + 3, t, 5))
    nw = 0
    for o in d.Objects:
        if hasattr(o, 'SourceTerminal') and not o.Shape.isNull():
            add(o.Shape, 1.0, (0.75, 0.22, 0.17)); nw += 1
    res['devices'] = ndev; res['wires'] = nw
    pw, ph = 1190.55, 841.89
    x0, x1, y0, y1 = min(xs) - 60, max(xs) + 60, min(ys) - 80, max(ys) + 120
    mx, top, bot = 40, 70, 90
    sc = min((pw - 2 * mx) / (x1 - x0), (ph - top - bot) / (y1 - y0))
    X = lambda x: mx + (x - x0) * sc
    Y = lambda y: bot + (y - y0) * sc
    pg = minipdf.Page(pw, ph)
    pg.rect(20, 20, pw - 40, ph - 40, 1.5)
    for pts, w, rgb in segs: pg.line([(X(a), Y(b)) for a, b in pts], w, rgb)
    for t in texts: pg.text(X(t[0]), Y(t[1]), t[2], t[3] if len(t) > 3 else 8)
    pg.rect(pw - 420, 20, 400, 62, 1.0)
    pg.text(pw - 410, 62, 'VFD-driven 3-phase motor: breaker, VFD, motor, and control row (ILLUSTRATIVE)', 9)
    pg.text(pw - 410, 48, 'Symbols are original illustrative shapes, not IEC/ANSI. Terminal marking after ABB catalogue.', 6.5)
    pg.text(pw - 410, 36, 'Generated by the CAD program. Not a design, not checked for rating or safety.', 6.5)
    pdf = OUT + '/vfd_motor_A3.pdf'; pg.save(pdf)
    res['pdf_bytes'] = os.path.getsize(pdf)
    d.saveAs(OUT + '/vf.FCStd')
    res['done'] = True
except Exception:
    res['error'] = traceback.format_exc()
json.dump(res, open(OUT + '/result6.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print(json.dumps(res, ensure_ascii=False))
