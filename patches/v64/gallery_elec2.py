    mx, top, bot = 40, 70, 90
    sc = min((pw - 2 * mx) / (x1 - x0), (ph - top - bot) / (y1 - y0))
    X = lambda x: mx + (x - x0) * sc
    Y = lambda y: bot + (y - y0) * sc
    pg = minipdf.Page(pw, ph)
    pg.rect(20, 20, pw - 40, ph - 40, 1.5)
    for pts, w, rgb in segs: pg.line([(X(a), Y(b)) for a, b in pts], w, rgb)
    for t in texts: pg.text(X(t[0]), Y(t[1]), t[2], t[3] if len(t) > 3 else 8)
    pg.rect(pw - 420, 20, 400, 62, 1.0)
