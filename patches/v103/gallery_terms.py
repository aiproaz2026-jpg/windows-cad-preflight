# -*- coding: utf-8 -*-
"""CI gallery for term_ends2: every library symbol with its terminal dots at lead ends, plus a
multi-terminal block chain wired pole to pole. Headless FreeCAD, CI only (Windows Server 2022,
Mesa software GL). Not a real-hardware test, not a design check. GPL-3.0-or-later."""
import sys, json, os, math, traceback
import FreeCAD as App
sys.path.insert(0, 'C:/DeltaTest/Mod'); sys.path.insert(0, 'C:/DeltaTest/Mod/DeltaEngineering')
sys.path.insert(0, 'C:/DeltaTest/Mod/DeltaEngineering/DeltaEngineering')
OUT = 'C:/seed/gallery72'; os.makedirs(OUT, exist_ok=True)
res = {'done': False}
try:
    from DeltaEngineering import term_ends2 as TE, symbols as S, minipdf
    from DeltaEngineering.symbols import create
    from DeltaEngineering.domain import add_terminal_wire, netlist
    from DeltaEngineering import routecheck
    res['table'] = TE.install()
    terminal_position = TE.terminal_position

    def stock(kind, i, n):
        return (60.0, 30.0 - 60.0 * (i + 1) / (n + 1))

    d = App.newDocument('TR')
    kinds = list(S.V60_LIB.keys())
    pw, ph = 1190.55, 841.89
    COLS, ROWS = 6, 4                      # 24 symbols per A3 page, fixed cell size (v95)
    PER = COLS * ROWS
    cellw, cellh, sc = 190, 135, 0.62
    npages = (len(kinds) + PER - 1) // PER
    pages = []

    def newpage(n):
        p = minipdf.Page(pw, ph)
        p.rect(20, 20, pw - 40, ph - 40, 1.5)
        p.text(40, ph - 45, 'Electrical symbol library: terminal dots at the end of each symbol lead (page %d of %d)' % (n, npages), 10)
        p.text(40, ph - 60, 'Vertical symbols (coils, contacts, 1P breaker) and multi-terminal blocks included. '
                            'Shapes are original illustrative drawings, not IEC/ANSI symbols.', 6.5)
        p.text(pw - 330, 34, 'Generated by the CAD program in CI. Not a design, not checked for rating or safety.', 6)
        pages.append(p)
        return p
    moved = 0; total = 0; stock_left = []; dupes = []; outside = []; per_symbol = {}
    pg = None
    for i, k in enumerate(kinds):
        if i % PER == 0:
            pg = newpage(i // PER + 1)
        j = i % PER
        o = create(d, k, 'T%d' % i, App.Vector(0, 0, 0))
        o.touch(); d.recompute()
        terms = [str(t) for t in o.Terminals]
        box = o.Shape.BoundBox
        cell_x = 40 + (j % COLS) * cellw + cellw / 2.0
        cell_top = ph - 100 - (j // COLS) * cellh
        cx = cell_x - (box.XMin + box.XMax) / 2.0 * sc
        cy = (cell_top - 52) - (box.YMin + box.YMax) / 2.0 * sc
        for e in o.Shape.Edges:
            if e.Curve.__class__.__name__ != 'Line':
                pp = [e.valueAt(e.FirstParameter + (e.LastParameter - e.FirstParameter) * n / 20.0) for n in range(21)]
            else:
                pp = [e.Vertexes[0].Point, e.Vertexes[-1].Point]
            pg.line([(cx + p.x * sc, cy + p.y * sc) for p in pp], 0.7, (0.08, 0.2, 0.35))
        pos = {}
        for n_, t in enumerate(terms):
            p = terminal_position(o, t)
            pos[t] = (round(p.x, 3), round(p.y, 3))
            total += 1
            if abs(p.x - stock(k, n_, len(terms))[0]) > 1e-6 or abs(p.y - stock(k, n_, len(terms))[1]) > 1e-6:
                moved += 1
            if not (box.XMin - 1.5 <= p.x <= box.XMax + 1.5 and box.YMin - 1.5 <= p.y <= box.YMax + 1.5):
                outside.append([k, t, pos[t]])
            dot = [(cx + (p.x + 4.0 * 0.7071 * math.cos(a)) * sc,
                    cy + (p.y + 4.0 * 0.7071 * math.sin(a)) * sc) for a in
                   [jj * 3.141592653589793 / 6 for jj in range(13)]]
            pg.line(dot, 0.9, (0.78, 0.16, 0.12))
            pg.text(cx + p.x * sc + 3, cy + p.y * sc + 2, t, 4.5, (0.6, 0.1, 0.05))
        if len(set(pos.values())) != len(pos):
            dupes.append(k)
        if all(abs(pos[t][0] - stock(k, n_, len(terms))[0]) < 1e-6 and
               abs(pos[t][1] - stock(k, n_, len(terms))[1]) < 1e-6 for n_, t in enumerate(terms)):
            stock_left.append(k)
        per_symbol[k] = pos
        label = k.replace(' (illustr.)', '')
        pg.text(cell_x - len(label) * 1.6, cell_top - cellh + 14, label, 6, (0.1, 0.1, 0.1))
    names = []
    for n_, p in enumerate(pages):
        fn = '/symbols_grid_A3.pdf' if n_ == 0 else '/symbols_grid_A3_p%d.pdf' % (n_ + 1)
        p.save(OUT + fn); names.append(fn[1:])
    res.update({'symbol_pages': names, 'pdf_symbols': os.path.getsize(OUT + '/symbols_grid_A3.pdf'), 'symbols': len(kinds),
                'terminals': total, 'terminals_moved': moved, 'stock_left': stock_left,
                'duplicate_positions': dupes, 'outside_bounds': outside})

    # multi-terminal block chain, drawn as a ladder: breaker 3P -> contactor 3P -> overload relay -> motor
    b = create(d, 'Breaker 3P (illustr.)', 'Q1', App.Vector(0, 640, 0))
    c = create(d, 'Contactor 3P (illustr.)', 'K1', App.Vector(0, 340, 0))
    ol = create(d, 'Overload relay (illustr.)', 'F1', App.Vector(0, 40, 0))
    m = create(d, 'Motor 3-phase (illustr.)', 'M1', App.Vector(260, -230, 0))
    n = 0
    for a_, b_ in [('2', '1L1'), ('4', '3L2'), ('6', '5L3')]:
        n += 1; add_terminal_wire(d, b, a_, c, b_, 'W%d' % n)
    for a_, b_ in [('2T1', '1L1'), ('4T2', '3L2'), ('6T3', '5L3')]:
        n += 1; add_terminal_wire(d, c, a_, ol, b_, 'W%d' % n)
    for a_, b_ in [('2T1', 'U1'), ('4T2', 'V1'), ('6T3', 'W1')]:
        n += 1; add_terminal_wire(d, ol, a_, m, b_, 'W%d' % n)
    d.recompute()
    # v100: route the block chain with wire_route (v12) and record overlaps before and after
    try:
        from DeltaEngineering import wire_route as WR
        res['block_overlaps_before'] = [list(o) for o in WR.overlaps(d)]
        rows_ = WR.reroute(d)
        d.recompute()
        res['block_overlaps_after'] = [list(o) for o in WR.overlaps(d)]
        res['block_reroute'] = [{k: r_.get(k) for k in ('wire', 'points', 'routed', 'strict', 'ms', 'reason', 'segments_in_foreign_box')} for r_ in rows_]
        res['block_wire_paths'] = {r_['wire']: r_.get('path') for r_ in rows_}
    except Exception:
        res['block_reroute_error'] = traceback.format_exc()
    res['block_netlist'] = len(netlist(d))
    res['block_route_findings'] = routecheck.check(d)['count']
    pg2 = minipdf.Page(pw, ph)
    pg2.rect(20, 20, pw - 40, ph - 40, 1.5)
    pg2.text(40, ph - 45, 'Multi-terminal blocks: terminals on the block edge, wired pole to pole', 10)
    pg2.text(40, ph - 60, 'Breaker 3P Q1 -> contactor 3P K1 -> overload F1 -> motor 3-phase M1. '
                          'Schematic only; no ratings, no protection coordination, no cable sizing.', 6.5)
    group = (b, c, ol, m)
    xs = []; ys = []
    for o in group:
        for e in o.Shape.Edges:
            if e.Curve.__class__.__name__ != 'Line':
                pp = [e.valueAt(e.FirstParameter + (e.LastParameter - e.FirstParameter) * j / 20.0) for j in range(21)]
            else:
                pp = [e.Vertexes[0].Point, e.Vertexes[-1].Point]
            xs += [p.x for p in pp]; ys += [p.y for p in pp]
    x0, x1, y0, y1 = min(xs) - 60, max(xs) + 60, min(ys) - 60, max(ys) + 60
    sc2 = min((pw - 160) / (x1 - x0), (ph - 220) / (y1 - y0))
    ox, oy = 80, 90
    X = lambda x: ox + (x - x0) * sc2
    Y = lambda y: oy + (y - y0) * sc2
    for o in d.Objects:
        if hasattr(o, 'SourceTerminal') and not o.Shape.isNull():
            for e in o.Shape.Edges:
                pp = [e.Vertexes[0].Point, e.Vertexes[-1].Point]
                pg2.line([(X(p.x), Y(p.y)) for p in pp], 1.4, (0.75, 0.22, 0.17))
    for o in group:
        for e in o.Shape.Edges:
            if e.Curve.__class__.__name__ != 'Line':
                pp = [e.valueAt(e.FirstParameter + (e.LastParameter - e.FirstParameter) * j / 20.0) for j in range(21)]
            else:
                pp = [e.Vertexes[0].Point, e.Vertexes[-1].Point]
            pg2.line([(X(p.x), Y(p.y)) for p in pp], 1.0, (0.08, 0.2, 0.35))
        pg2.text(X(o.Position.x) - 22, Y(o.Position.y + 62), o.Tag, 9)
        for t in o.Terminals:
            p = terminal_position(o, t)
            dot = [(X(p.x) + 4.2 * math.cos(a), Y(p.y) + 4.2 * math.sin(a)) for a in
                   [j * math.pi / 6 for j in range(13)]]
            pg2.line(dot, 1.0, (0.78, 0.16, 0.12))
            pg2.text(X(p.x) + 5, Y(p.y) + 3, t, 6, (0.6, 0.1, 0.05))
    tx = max(X(x1) + 50, 640)
    ty = ph - 110
    pg2.text(tx, ty, 'Terminal positions used by the drawing (mm from each block origin)', 8)
    ty -= 18
    for o in group:
        pg2.text(tx, ty, '%s  %s' % (o.Tag, str(o.DeviceType).replace(' (illustr.)', '')), 8, (0.08, 0.2, 0.35))
        ty -= 13
        for t in o.Terminals:
            p = terminal_position(o, t)
            pg2.text(tx + 14, ty, '%s  (%.2f, %.2f)' % (t, p.x - o.Position.x, p.y - o.Position.y), 7, (0.25, 0.25, 0.25))
            ty -= 12
        ty -= 6
    pg2.text(tx, ty - 6, 'Wires: %d.  Netlist entries: %d.' % (n, res['block_netlist']), 7, (0.25, 0.25, 0.25))
    pg2.text(pw - 330, 34, 'Generated by the CAD program in CI. Not a design, not checked for rating or safety.', 6)
    pg2.save(OUT + '/blocks_A3.pdf')
    res['pdf_blocks'] = os.path.getsize(OUT + '/blocks_A3.pdf')
    res['per_symbol'] = per_symbol
    d.saveAs(OUT + '/terms.FCStd')
    res['done'] = True
except Exception:
    res['error'] = traceback.format_exc()
json.dump(res, open(OUT + '/result.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print(json.dumps({k: v for k, v in res.items() if k != 'per_symbol'}, ensure_ascii=False))
